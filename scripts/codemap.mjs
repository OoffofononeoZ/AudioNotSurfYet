import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { AREAS, ROOT, byText, contained, listFiles, markdownLink, readText } from './lib/repository.mjs';
import { inspectSources } from './lib/source-map.mjs';

// Deterministic, paginated code navigation; all output is owned by this generator.
export const MARKER = '<!-- Generated by scripts/codemap.mjs; do not edit manually. -->';
const MAP = 'docs/CODEMAP.md';
const DETAIL_DIRECTORY = 'docs/codemap';
const PAGE_SIZE = 100;

function sourcePage(file, title, records) {
  const lines = [MARKER, '', `# ${title}`, '', '只列可识别的本地文件引用；不是完整调用图。', '', '| 文件 | 本地静态引用（最多显示 6 项） |', '| --- | --- |'];
  for (const record of records) {
    const references = record.imports.slice(0, 6).map(target => markdownLink(file, target));
    if (record.imports.length > 6) references.push(`另 ${record.imports.length - 6} 项，按需核对源码`);
    lines.push(`| ${markdownLink(file, record.file)} | ${references.join('、') || '—'} |`);
  }
  return `${lines.join('\n')}\n`;
}

export function buildMaps(root) {
  const files = listFiles(root);
  const records = inspectSources(root, files);
  const output = new Map();
  const overview = [MARKER, '', '# 代码地图', '', '由当前文件与有限静态引用生成。优先按区域打开子地图，再用 `rg` 定位；不默认读取全部文件。', '',
    '支持 Vue script 与常见 JS/TS 静态及字面量导入；不分析动态表达式、完整符号调用链、任意别名或运行时注册。', '源码别名当前仅识别 `@/` → `src/`；其他别名以实际代码为准。', '', '## 当前应用状态', ''];
  if (!records.some(record => !['tooling', 'tests'].includes(record.area))) {
    overview.push('尚无应用源码，现有源码为开发工具及其验证。');
  } else {
    overview.push('下表列出实际存在的代码区域；人工维护的职责与设计解释见 system map；运行方法与验证入口见根 README。');
  }
  overview.push('', '## 代码区域', '', '| 区域 | 文件数 | 入口 |', '| --- | --- | --- |');
  for (const area of AREAS) {
    const members = records.filter(record => record.area === area.id);
    if (!members.length) continue;
    const landing = `${DETAIL_DIRECTORY}/${area.id}.md`;
    if (members.length <= PAGE_SIZE) output.set(landing, sourcePage(landing, area.title, members));
    else {
      const links = [];
      for (let start = 0; start < members.length; start += PAGE_SIZE) {
        const page = `${DETAIL_DIRECTORY}/${area.id}-${Math.floor(start / PAGE_SIZE) + 1}.md`;
        output.set(page, sourcePage(page, area.title, members.slice(start, start + PAGE_SIZE)));
        links.push(`- ${markdownLink(landing, page, `第 ${links.length + 1} 页`)}`);
      }
      output.set(landing, `${[MARKER, '', `# ${area.title}`, '', '按需读取，每页最多 100 个文件。', '', ...links].join('\n')}\n`);
    }
    overview.push(`| ${area.title} | ${members.length} | ${markdownLink(MAP, landing, '模块地图')} |`);
  }
  overview.push('', '## 规范与资料入口', '');
  for (const file of ['AGENTS.md', 'README.md', 'docs/context/index.md', 'docs/context/system-map.md']) {
    if (files.includes(file)) overview.push(`- ${markdownLink(MAP, file)}`);
  }
  const skills = files.filter(file => /^skills\/[^/]+\/SKILL\.md$/.test(file));
  if (skills.length) overview.push('', '## 按任务读取的 skills', '');
  for (const file of skills) overview.push(`- ${markdownLink(MAP, file, file.split('/')[1])}`);
  output.set(MAP, `${overview.join('\n')}\n`);
  return output;
}

function oldGeneratedFiles(root) {
  const directory = contained(root, DETAIL_DIRECTORY);
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory).sort(byText).filter(name => name.endsWith('.md'))
    .map(name => `${DETAIL_DIRECTORY}/${name}`)
    .filter(file => fs.lstatSync(contained(root, file)).isFile() && readText(root, file).startsWith(MARKER));
}

export function staleMaps(root, output = buildMaps(root)) {
  const stale = [];
  for (const [file, expected] of output) {
    const target = contained(root, file);
    if (!fs.existsSync(target) || readText(root, file) !== expected) stale.push(file);
  }
  for (const file of oldGeneratedFiles(root)) if (!output.has(file)) stale.push(file);
  return stale.sort(byText);
}

export function generateMaps(root) {
  const output = buildMaps(root);
  const changed = staleMaps(root, output);
  // Reject collisions rather than overwriting manually maintained documents.
  for (const file of changed) {
    const target = contained(root, file);
    if (fs.existsSync(target) && !readText(root, file).startsWith(MARKER)) {
      throw new Error(`生成路径已有非生成文档：${file}`);
    }
  }
  for (const file of changed) {
    const target = contained(root, file);
    if (!output.has(file)) fs.unlinkSync(target);
    else {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, output.get(file), 'utf8');
    }
  }
  return changed;
}

export function main(args = process.argv.slice(2)) {
  if (args.some(arg => arg !== '--check')) throw new Error('用法：node scripts/codemap.mjs [--check]');
  if (args.includes('--check')) {
    const stale = staleMaps(ROOT);
    if (stale.length) {
      console.error(`代码地图过期：\n${stale.join('\n')}\n请运行 npm run codemap`);
      return 1;
    }
    console.log('代码地图一致。');
  } else {
    const changed = generateMaps(ROOT);
    console.log(`代码地图更新 ${changed.length} 个文件。`);
  }
  return 0;
}

