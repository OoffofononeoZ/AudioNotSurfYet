import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { ROOT, byText, contained, readText, skillMetadata } from './lib/repository.mjs';

export const MARKER = 'Generated by scripts/install-project-skills.mjs; do not edit manually.';
const DISCOVERY = '.agents/skills';

function expectedEntries(root) {
    const expected = new Map();
    for (const name of fs.readdirSync(contained(root, 'skills')).sort(byText)) {
        const source = `skills/${name}/SKILL.md`;
        if (!fs.existsSync(contained(root, source))) continue;
        const metadata = skillMetadata(readText(root, source));
        if (metadata.name !== name || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name) || name.length > 64)
            throw new Error(`skill 名称与目录不一致或不合法：${name}`);
        expected.set(
            `${DISCOVERY}/${name}/SKILL.md`,
            `---\nname: ${name}\ndescription: ${JSON.stringify(metadata.description)}\n---\n\n<!-- ${MARKER} -->\n\n使用本 skill 时，先完整读取[项目维护源](../../../${source})，再按任务读取其中引用的资料。\n每次读取文档、skill 及引用文本必须显式指定 UTF-8 编码参数；PowerShell 使用 \`Get-Content -Encoding UTF8\`，内容检索使用 \`rg --encoding utf-8\`。工具不支持时换用支持显式编码的方式，不依赖默认编码或控制台设置；仅列文件名无需编码参数。\n本文件只负责 AudioNotSurfYet 仓库内发现，不替代维护源。\n`,
        );
        const yaml = `skills/${name}/agents/openai.yaml`;
        if (fs.existsSync(contained(root, yaml)))
            expected.set(`${DISCOVERY}/${name}/agents/openai.yaml`, `# ${MARKER}\n${readText(root, yaml)}`);
    }
    return { expected, count: [...expected.keys()].filter(file => file.endsWith('/SKILL.md')).length };
}

function generatedEntries(root) {
    const result = [];
    if (!fs.existsSync(contained(root, DISCOVERY))) return result;
    for (const name of fs.readdirSync(contained(root, DISCOVERY)).sort(byText)) {
        for (const suffix of ['SKILL.md', 'agents/openai.yaml']) {
            const file = `${DISCOVERY}/${name}/${suffix}`;
            if (
                fs.existsSync(contained(root, file)) &&
                fs.lstatSync(contained(root, file)).isFile() &&
                readText(root, file).includes(MARKER)
            )
                result.push(file);
        }
    }
    return result;
}

export function installProjectSkills(root = ROOT, check = false) {
    const { expected, count } = expectedEntries(root);
    const changes = [];
    for (const [file, content] of expected) {
        const exists = fs.existsSync(contained(root, file));
        if (exists && readText(root, file) === content) continue;
        if (exists && !readText(root, file).includes(MARKER)) throw new Error(`保留非本工具生成的文件：${file}`);
        changes.push(file);
    }
    for (const file of generatedEntries(root)) if (!expected.has(file)) changes.push(file);
    if (check && changes.length)
        throw new Error(`项目 skill 入口缺失或过期：${changes.join('、')}；运行 npm run skills:install`);
    for (const file of changes) {
        const target = contained(root, file);
        if (!expected.has(file)) fs.unlinkSync(target);
        else {
            fs.mkdirSync(path.dirname(target), { recursive: true });
            fs.writeFileSync(target, expected.get(file), 'utf8');
        }
    }
    return count;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
    try {
        if (process.argv.slice(2).some(arg => arg !== '--check'))
            throw new Error('用法：node scripts/install-project-skills.mjs [--check]');
        console.log(
            `项目 skills ${process.argv.includes('--check') ? '检查' : '同步'}完成：${installProjectSkills(ROOT, process.argv.includes('--check'))} 个。`,
        );
    } catch (error) {
        console.error(error.message);
        process.exitCode = 1;
    }
}
